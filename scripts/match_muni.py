import unicodedata

def strip_accents(s: str) -> str:
    return ''.join(c for c in unicodedata.normalize('NFD', s)
                   if unicodedata.category(c) != 'Mn')

def normalize_hyphens(s: str) -> str:
    return s.replace(' - ', '-').replace(' – ', '-')

def to_partial(name: str) -> str:
    """Simulate the mojibake encoding loss: returns the partially decoded string."""
    result = []
    for char in name:
        cp = ord(char)
        if 0x0370 <= cp <= 0x03FF:
            utf8 = char.encode('utf-8')
            if len(utf8) == 2:
                b1, b2 = utf8[0], utf8[1]
                if b1 == 0xCE and 0xA0 <= b2 <= 0xBF:
                    result.append(chr((0x0E << 6) | (b2 & 0x3F)))
                else:
                    result.append('?')
            else:
                result.append('?')
        else:
            result.append(char)
    return ''.join(result)


def decode_file_name(s: str) -> str:
    """Partial decode of mojibake string (from file)."""
    chars = list(s)
    result = []
    i = 0
    while i < len(chars):
        cp = ord(chars[i])
        if cp == 0x00CE:
            if i + 1 < len(chars):
                next_cp = ord(chars[i+1])
                if 0x00A0 <= next_cp <= 0x00BF:
                    # Normal visible Greek char
                    result.append(chr((0x0E << 6) | (next_cp & 0x3F)))
                    i += 2
                    continue
                elif next_cp == 0x0020:
                    # NBSP was normalized to space → this is Π
                    result.append('Π')
                    i += 2
                    continue
            result.append('?')
            i += 1
        elif cp == 0x00CF:
            result.append('?')
            i += 1
        else:
            result.append(chars[i])
            i += 1
    return ''.join(result)


def make_key(s: str) -> str:
    """Normalize for matching: strip accents from visible letters, normalize hyphens."""
    return normalize_hyphens(strip_accents(s))


